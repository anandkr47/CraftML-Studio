"""
Docker Image Builder for Model Deployment
Creates Docker images for model inference APIs
"""

import os
import subprocess
from typing import Dict, Any, Optional
from pathlib import Path
import logging

logger = logging.getLogger(__name__)


class DockerBuilder:
    """
    Builds Docker images for model deployment
    """
    
    def __init__(self):
        self.base_images = {
            "cpu": "python:3.10-slim",
            "gpu": "nvidia/cuda:11.8.0-cudnn8-runtime-ubuntu22.04"
        }
    
    def create_dockerfile(
        self,
        model_path: str,
        output_dir: str,
        device: str = "cpu",
        port: int = 8000
    ) -> str:
        """
        Create Dockerfile for model serving
        
        Args:
            model_path: Path to model
            output_dir: Directory to create Dockerfile in
            device: 'cpu' or 'gpu'
            port: Port to expose
            
        Returns:
            Path to created Dockerfile
        """
        os.makedirs(output_dir, exist_ok=True)
        dockerfile_path = os.path.join(output_dir, "Dockerfile")
        
        base_image = self.base_images.get(device, self.base_images["cpu"])
        
        dockerfile_content = f'''FROM {base_image}

# Set working directory
WORKDIR /app

# Install system dependencies
RUN apt-get update && apt-get install -y \\
    build-essential \\
    curl \\
    && rm -rf /var/lib/apt/lists/*

# Install Python dependencies
RUN pip install --no-cache-dir \\
    fastapi \\
    uvicorn[standard] \\
    transformers \\
    torch \\
    accelerate \\
    pydantic

# Copy model files
COPY model /app/model

# Copy inference server
COPY server.py /app/server.py

# Expose port
EXPOSE {port}

# Health check
HEALTHCHECK --interval=30s --timeout=10s --start-period=60s --retries=3 \\
    CMD curl -f http://localhost:{port}/health || exit 1

# Run server
CMD ["uvicorn", "server:app", "--host", "0.0.0.0", "--port", "{port}"]
'''
        
        with open(dockerfile_path, 'w') as f:
            f.write(dockerfile_content)
        
        logger.info(f"Dockerfile created: {dockerfile_path}")
        
        return dockerfile_path
    
    def create_inference_server(
        self,
        output_dir: str,
        port: int = 8000
    ) -> str:
        """
        Create FastAPI inference server script
        
        Args:
            output_dir: Directory to create server.py in
            port: Server port
            
        Returns:
            Path to server.py
        """
        server_path = os.path.join(output_dir, "server.py")
        
        server_content = '''"""
FastAPI Inference Server
Auto-generated by CraftML Studio
"""

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from transformers import AutoModelForCausalLM, AutoTokenizer, pipeline
import torch
import logging

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

app = FastAPI(title="Model Inference API")

# Global model and tokenizer
model = None
tokenizer = None
pipe = None

class InferenceRequest(BaseModel):
    prompt: str
    max_length: int = 100
    temperature: float = 0.7
    top_p: float = 0.9
    top_k: int = 50

class InferenceResponse(BaseModel):
    generated_text: str
    prompt: str

@app.on_event("startup")
async def load_model():
    global model, tokenizer, pipe
    
    logger.info("Loading model...")
    
    model_path = "/app/model"
    
    try:
        model = AutoModelForCausalLM.from_pretrained(
            model_path,
            torch_dtype=torch.float16,
            device_map="auto"
        )
        
        tokenizer = AutoTokenizer.from_pretrained(model_path)
        
        pipe = pipeline(
            "text-generation",
            model=model,
            tokenizer=tokenizer,
            device_map="auto"
        )
        
        logger.info("Model loaded successfully")
        
    except Exception as e:
        logger.error(f"Failed to load model: {str(e)}")
        raise

@app.get("/")
async def root():
    return {
        "status": "running",
        "model": "loaded" if model is not None else "not_loaded",
        "endpoints": ["/generate", "/health"]
    }

@app.get("/health")
async def health():
    return {
        "status": "healthy" if model is not None else "unhealthy",
        "model_loaded": model is not None
    }

@app.post("/generate", response_model=InferenceResponse)
async def generate(request: InferenceRequest):
    if pipe is None:
        raise HTTPException(status_code=500, detail="Model not loaded")
    
    try:
        result = pipe(
            request.prompt,
            max_length=request.max_length,
            temperature=request.temperature,
            top_p=request.top_p,
            top_k=request.top_k,
            num_return_sequences=1
        )
        
        return InferenceResponse(
            generated_text=result[0]["generated_text"],
            prompt=request.prompt
        )
        
    except Exception as e:
        logger.error(f"Generation failed: {str(e)}")
        raise HTTPException(status_code=500, detail=str(e))

if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)
'''
        
        with open(server_path, 'w') as f:
            f.write(server_content)
        
        logger.info(f"Server script created: {server_path}")
        
        return server_path
    
    def create_docker_compose(
        self,
        output_dir: str,
        image_name: str,
        port: int = 8000,
        device: str = "cpu"
    ) -> str:
        """
        Create docker-compose.yml for easy deployment
        
        Args:
            output_dir: Directory to create file in
            image_name: Docker image name
            port: Port mapping
            device: 'cpu' or 'gpu'
            
        Returns:
            Path to docker-compose.yml
        """
        compose_path = os.path.join(output_dir, "docker-compose.yml")
        
        if device == "gpu":
            runtime = '''
    runtime: nvidia
    environment:
      - NVIDIA_VISIBLE_DEVICES=all'''
        else:
            runtime = ""
        
        compose_content = f'''version: '3.8'

services:
  model-server:
    image: {image_name}
    container_name: model-inference
    ports:
      - "{port}:{port}"
    restart: unless-stopped{runtime}
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:{port}/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 60s
'''
        
        with open(compose_path, 'w') as f:
            f.write(compose_content)
        
        logger.info(f"docker-compose.yml created: {compose_path}")
        
        return compose_path
    
    def build_image(
        self,
        model_path: str,
        image_name: str,
        output_dir: str,
        device: str = "cpu",
        port: int = 8000
    ) -> Dict[str, Any]:
        """
        Build Docker image for model deployment
        
        Args:
            model_path: Path to model
            image_name: Name for Docker image
            output_dir: Directory to build in
            device: 'cpu' or 'gpu'
            port: Port to expose
            
        Returns:
            Build result
        """
        try:
            logger.info(f"Building Docker image: {image_name}")
            
            # Create build directory
            build_dir = os.path.join(output_dir, "docker_build")
            os.makedirs(build_dir, exist_ok=True)
            
            # Copy model to build directory
            import shutil
            model_dest = os.path.join(build_dir, "model")
            if os.path.exists(model_dest):
                shutil.rmtree(model_dest)
            shutil.copytree(model_path, model_dest)
            
            # Create Dockerfile
            self.create_dockerfile(model_path, build_dir, device, port)
            
            # Create server script
            self.create_inference_server(build_dir, port)
            
            # Create docker-compose.yml
            self.create_docker_compose(output_dir, image_name, port, device)
            
            # Build Docker image
            build_cmd = [
                "docker", "build",
                "-t", image_name,
                "-f", os.path.join(build_dir, "Dockerfile"),
                build_dir
            ]
            
            logger.info(f"Running: {' '.join(build_cmd)}")
            
            result = subprocess.run(
                build_cmd,
                capture_output=True,
                text=True,
                cwd=build_dir,
                timeout=1800  # 30 minutes
            )
            
            if result.returncode != 0:
                logger.error(f"Docker build failed: {result.stderr}")
                return {
                    "status": "failed",
                    "error": result.stderr
                }
            
            logger.info(f"Docker image built successfully: {image_name}")
            
            return {
                "status": "success",
                "image_name": image_name,
                "build_dir": build_dir,
                "dockerfile": os.path.join(build_dir, "Dockerfile"),
                "docker_compose": os.path.join(output_dir, "docker-compose.yml"),
                "usage": {
                    "run": f"docker run -p {port}:{port} {image_name}",
                    "compose": f"cd {output_dir} && docker-compose up -d"
                }
            }
            
        except subprocess.TimeoutExpired:
            logger.error("Docker build timed out")
            return {
                "status": "failed",
                "error": "Docker build timed out after 30 minutes"
            }
        except Exception as e:
            logger.error(f"Docker build failed: {str(e)}")
            return {
                "status": "failed",
                "error": str(e)
            }
    
    def check_docker(self) -> bool:
        """Check if Docker is available"""
        try:
            result = subprocess.run(
                ["docker", "--version"],
                capture_output=True,
                timeout=5
            )
            return result.returncode == 0
        except:
            return False


# Global builder instance
docker_builder = DockerBuilder()

